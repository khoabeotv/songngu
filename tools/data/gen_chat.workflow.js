const isEval = args.set === "eval";
const part = args.part || 0;
const topics = isEval ? evalTopics : parts[part];
const batch = args.batch || 1;
const tasks = [];
for (let i = 0; i < topics.length; i++) {
  const key = (isEval ? "eval" : "own-p" + part) + "-b" + batch + "-" + String(i).padStart(2, "0");
  tasks.push({
    key: key,
    label: "Generate " + key,
    agent: "delegate",
    model: "anthropic/claude-haiku-4-5:off",
    task: (args.prompt || PROMPT).replace("{topic}", topics[i]) + "\n\n" +
      "Đây là lượt " + batch + " cho chủ đề này: chọn tình huống, con người và cách nói khác với câu trả lời đầu tiên thường gặp.\n" +
      "Trả lời thẳng bằng các tin nhắn trong câu trả lời. Không dùng tool, không đọc hay ghi file, không mở đầu hay kết luận.",
    output: (isEval ? "chateval/" : "chatown/") + key + ".txt"
  });
}
const res = await runs.all(tasks);
let ok = 0;
for (let j = 0; j < res.length; j++) {
  if (res[j].ok) ok++;
}
return { set: isEval ? "eval" : "train", part: part, batch: batch, ok: ok, total: res.length };
